def _norm(s):
    return re.sub(r"[^a-z0-9]", "", str(s).lower())


def find_gift(name):
    if not name:
        return None
    target = _norm(name)
    for g in GIFTS:
        if _norm(g[0]) == target:
            return g
    return None


def gift_from_points(points):
    if not GIFTS:
        return None
    chosen = GIFTS[0]
    for g in GIFTS:
        if points >= g[2]:
            chosen = g
    return chosen


def get_points(name):
    g = find_gift(name)
    return g[2] if g else 0


def get_icon(name):
    g = find_gift(name)
    return g[1] if g else '🎁'


def get_effect(name):
    g = find_gift(name)
    return g[3] if g else 'text'


def get_folder(name):
    g = find_gift(name)
    return g[4] if g else ''


def list_fx_gifts():
    return [(g[0], g[1], g[2], g[4]) for g in GIFTS if g[3] == 'fx']


def list_text_gifts():
    return [(g[0], g[1], g[2], g[4]) for g in GIFTS if g[3] == 'text']